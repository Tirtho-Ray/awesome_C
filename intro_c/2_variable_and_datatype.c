#include<stdio.h>

// c has many data types like int, float, double, char, etc.

//  ------- Example  --------- 
// 1: int  = 10; // integer data type
// 2: float = 10.5; // float data type
// 3: double = 10.5; // double data type
// 4: char = 'a'; // character data type


int main() {
    int a = 10; // integer data type
    float b = 10.5; // float data type
    double c = 10.5; // double data type
    char d = 'a'; // character data type
    printf("The value of a is %d\n", a);
    printf("The value of b is %f\n", b);
    printf("The value of c is %lf\n", c);
    printf("The value of d is %c\n", d);
    // sizeof(a);
    printf("The size of a is %zu bytes\n", sizeof(a));

    return 0;
}


// int , float , double, char 


